/** A label in every supported locale. Totality is enforced by `Record<Locale, string>`. */
export type LocalisedLabels = Readonly<Record<Locale, string>>;

/** One top-level group of the taxonomy. */
export interface IndustryGroup {
  readonly key: IndustryGroupKey;
  readonly labels: LocalisedLabels;
  readonly icon: IndustryIcon;
}

/** One leaf industry. */
export interface Industry {
  /** Stable key. Written to `sites.industry_key`; never renamed, because it is a join key. */
  readonly key: string;
  readonly groupKey: IndustryGroupKey;
  readonly labels: LocalisedLabels;
  /**
   * Dutch and English aliases for the combobox, lowercase.
   *
   * These are *search* terms, not synonyms shown to the user: misspellings, regional words and the
   * English name all belong here, because the cost of a missing alias is a user who cannot find
   * their own trade in the list and abandons onboarding at step one.
   */
  readonly searchTerms: readonly string[];
  readonly icon: IndustryIcon;
  /** Validated `LocalBusiness` subtype for the JSON-LD `@graph`. */
  readonly schemaOrgType: SchemaOrgType;
  /**
   * A Wikidata or schema.org URI carrying the meaning `schemaOrgType` had to drop, or `null`.
   *
   * Emitted as `additionalType`. This is the honest alternative to inventing a `@type`: the graph
   * stays valid, rich results keep working, and the specific trade is still stated.
   */
  readonly additionalType: string | null;
  readonly dnaId: DnaId;
}

