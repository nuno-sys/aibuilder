/**
 * The curated industry taxonomy: 14 groups, 104 leaves.
 *
 * This table mirrors `industry_groups` / `industries` / `industry_translations` in the control
 * plane, and it is load-bearing in four different places, which is why it is data and not a switch
 * statement:
 *
 *   1. **The onboarding combobox.** `GET /v1/bootstrap` returns `{key, groupKey, label,
 *      searchTerms, icon}` straight from here. `searchTerms` carries Dutch *and* English aliases because a Dutch
 *      user types `kapper` and an expat types `hairdresser`, and neither should get zero results.
 *   2. **The JSON-LD `@type`.** `schemaOrgType` is a real `LocalBusiness` subtype, verified
 *      against schema.org and never invented. Architecture §7.12: an invented type (`DJService`) silently
 *      disables every rich result on the page, so a DJ is a `ProfessionalService`. `SchemaOrgType`
 *      is a closed union, which makes "this industry's type is in the allowlist" a *compile-time*
 *      guarantee rather than a test.
 *   3. **`additionalType`.** Where no subtype is apt, the type falls back and the specific meaning
 *      is carried by a Wikidata or schema.org URI instead of a fabricated `@type`.
 *   4. **The design DNA.** `dnaId` picks one of the four Phase 1 archetypes. The full 20-preset
 *      registry from the design dimension lands in Phase 2; each of those presets maps onto one of
 *      these four (`espresso-warm`, `gold-heritage`, `market-fresh` and `paper-craft` all reduce to
 *      `warm_trattoria`, `hi-vis-utility` and `steel-industrial` to `garage_steel`, and so on), so
 *      Phase 2 refines this column instead of rewriting it.
 *
 * Display order is array order; the D1 `sort_order` of a row is its index × 10.
 */

