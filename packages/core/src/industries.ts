/** Index built once at module load; the combobox and the submit path both hit it per request. */
const INDUSTRY_BY_KEY: ReadonlyMap<string, Industry> = new Map(
  INDUSTRIES.map((industry) => [industry.key, industry]),
);

/** Index of groups by key. */
const GROUP_BY_KEY: ReadonlyMap<string, IndustryGroup> = new Map(
  INDUSTRY_GROUPS.map((group) => [group.key, group]),
);

/**
 * Looks up an industry by key, or `null`.
 *
 * Returns `null` rather than throwing because the caller is usually validating untrusted input (an
 * `industryKey` off the wire); use `assertIndustry()` where a missing row means our own data is
 * inconsistent.
 */
export function industryByKey(key: string): Industry | null {
  return INDUSTRY_BY_KEY.get(key) ?? null;
}

/** Looks up a group by key, or `null`. */
export function industryGroupByKey(key: string): IndustryGroup | null {
  return GROUP_BY_KEY.get(key) ?? null;
}

/** Every industry in one group, in display order. */
export function industriesByGroup(groupKey: IndustryGroupKey): readonly Industry[] {
  return INDUSTRIES.filter((industry) => industry.groupKey === groupKey);
}

/**
 * The D1 `sort_order` for an industry, or `null` when the key is unknown.
 *
 * Derived from array position (index × 10) so display order lives in exactly one place and the seed
 * migration cannot drift from the UI.
 */
export function industrySortOrder(key: string): number | null {
  const index = INDUSTRIES.findIndex((industry) => industry.key === key);
  return index === -1 ? null : index * 10;
}

/** Narrows an untrusted string to a value in the schema.org allowlist. */
export function isSchemaOrgType(value: unknown): value is SchemaOrgType {
  return typeof value === 'string' && (SCHEMA_ORG_TYPES as readonly string[]).includes(value);
}

/**
 * Looks up an industry by key or throws.
 *
 * For paths where a missing row means *our* data is inconsistent — a `sites.industry_key` read back
 * from D1, a taxonomy key inside a stored `SiteDoc` — rather than a bad request.
 */
export function assertIndustry(key: string): Industry {
  const industry = industryByKey(key);
  if (industry === null) throw new UnknownIndustryError(key);
  return industry;
}
