/**
 * Stages the brand clip into the marketing site.
 *
 * The sales page promises a full-screen video header that loads instantly. It has to keep that
 * promise on itself first, and it has to keep it with the SAME bytes a customer's site gets —
 * same encoder, same budgets, same ladder. So the marketing hero is not encoded by hand: it is the
 * `brand` clip out of the media library, copied into `public/` and described by a generated module.
 *
 * Two things come out of one run:
 *
 *   apps/marketing/public/media/hero/*                      the binaries Astro will fingerprint
 *   apps/marketing/src/content/hero-media.generated.ts      the sizes, keys and byte budgets
 *
 * Both are committed. The marketing build then needs no ffmpeg, no library checkout and no network
 * — which is the difference between a hero that renders in CI and the hero this repo used to have,
 * whose files existed only in a comment.
 *
 *   node scripts/media-library/stage-marketing.mjs
 */
import { execFileSync } from 'node:child_process';
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const OUT = path.join(ROOT, '.media-library', 'out');
const MANIFEST = path.join(ROOT, '.media-library', 'media-library.json');
const PUBLIC = path.join(ROOT, 'apps/marketing/public/media/hero');
const TARGET = path.join(ROOT, 'apps/marketing/src/content/hero-media.generated.ts');

/** The URL prefix the staged files are served under. */
const BASE = '/media/hero';

function fail(message) {
  console.error(message);
  process.exit(1);
}

if (!existsSync(MANIFEST)) {
  fail(`no manifest at ${path.relative(ROOT, MANIFEST)} — run ingest.mjs first`);
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const clip = (manifest.brand ?? [])[0];
if (clip === undefined) {
  fail('the manifest has no brand clip — run ingest.mjs --synthesize, or add sources/brand/');
}

mkdirSync(PUBLIC, { recursive: true });

/** Copies one library key into `public/`, flattened, and returns its public URL. */
function stage(key) {
  const from = path.join(OUT, key);
  if (!existsSync(from)) {
    fail(`missing rendition ${key} — re-run ingest.mjs`);
  }
  const name = path.basename(key);
  copyFileSync(from, path.join(PUBLIC, name));
  return { url: `${BASE}/${name}`, bytes: statSync(from).size };
}

function stageVideo(rendition) {
  const av1 = stage(rendition.av1Key);
  const h264 = stage(rendition.h264Key);
  return {
    av1: av1.url,
    h264: h264.url,
    width: rendition.width,
    height: rendition.height,
    maxBytes: Math.max(av1.bytes, h264.bytes),
  };
}

function stagePoster(poster) {
  for (const width of poster.widths) {
    stage(poster.avifKeyTemplate.replace('{width}', String(width)));
    stage(poster.webpKeyTemplate.replace('{width}', String(width)));
  }
  const toSrcset = (template) =>
    poster.widths
      .map(
        (width) => `${BASE}/${path.basename(template.replace('{width}', String(width)))} ${width}w`,
      )
      .join(', ');
  return {
    avifSrcset: toSrcset(poster.avifKeyTemplate),
    webpSrcset: toSrcset(poster.webpKeyTemplate),
    fallback: `${BASE}/${path.basename(poster.webpKeyTemplate.replace('{width}', String(poster.widths.at(-1))))}`,
    width: poster.width,
    height: poster.height,
  };
}

const landscape = stageVideo(clip.landscape);
const portrait = stageVideo(clip.portrait);
const poster = stagePoster(clip.poster);
const posterPortrait = stagePoster(clip.posterPortrait);

const module = `/**
 * GENERATED by scripts/media-library/stage-marketing.mjs — do not edit by hand.
 *
 * The brand clip's staged renditions: URLs under \`${BASE}\`, intrinsic sizes as encoded, and the
 * measured byte cost of the heaviest codec at each shape. \`hero-media.ts\` is where these numbers
 * acquire meaning — it holds the LCP size invariant they have to satisfy.
 *
 * Source clip: ${clip.id} (${clip.luminance}${clip.hue === null ? '' : `, hue ${clip.hue}`})
 */

export interface GeneratedVideo {
  readonly av1: string;
  readonly h264: string;
  readonly width: number;
  readonly height: number;
  /** Bytes of the larger of the two codecs, measured at encode time. */
  readonly maxBytes: number;
}

export interface GeneratedPoster {
  readonly avifSrcset: string;
  readonly webpSrcset: string;
  /** Largest WebP rung: the \`<img>\` src, decodable by every UA that reaches this markup. */
  readonly fallback: string;
  readonly width: number;
  readonly height: number;
}

export const brandPoster: GeneratedPoster = ${JSON.stringify(poster, null, 2)};

/** The 9:16 crop. Its rungs are all larger than a phone hero is displayed at — see \`hero-media.ts\`. */
export const brandPosterPortrait: GeneratedPoster = ${JSON.stringify(posterPortrait, null, 2)};

export const brandLandscape: GeneratedVideo = ${JSON.stringify(landscape, null, 2)};

export const brandPortrait: GeneratedVideo = ${JSON.stringify(portrait, null, 2)};

/** Measured off the pixels, not declared: it decides whether the scrim washes white or black. */
export const brandLuminance = ${JSON.stringify(clip.luminance)} as const;

export const brandCredit: string | null = ${JSON.stringify(clip.credit ?? null)};
`;

writeFileSync(TARGET, module);
format(TARGET);

const total = landscape.maxBytes + portrait.maxBytes;
console.log(
  `staged ${clip.id} -> ${path.relative(ROOT, PUBLIC)} ` +
    `(${Math.round(landscape.maxBytes / 1024)} kB landscape + ${Math.round(portrait.maxBytes / 1024)} kB portrait ` +
    `= ${Math.round(total / 1024)} kB) and ${path.relative(ROOT, TARGET)}`,
);

/**
 * Formats a generated file with the repository's own prettier.
 *
 * Without this the file lands in git as raw `JSON.stringify` output — double-quoted keys, no
 * trailing commas — and `pnpm format:check` fails on a file nobody wrote by hand. It only ever
 * passed before because a human ran `pnpm format` afterwards; a workflow does not, and commits the
 * unformatted version. Missing prettier is not fatal: the file is still correct, just ugly.
 */
function format(file) {
  const prettier = path.join(ROOT, 'node_modules/.bin/prettier');
  if (!existsSync(prettier)) {
    return;
  }
  try {
    execFileSync(prettier, ['--write', file], { stdio: 'ignore' });
  } catch {
    // A formatting failure must not lose the generated file that is already written.
  }
}
