/**
 * Turns the ingest manifest into a TypeScript module the Workers bundle.
 *
 * WHY BUNDLE IT RATHER THAN FETCH IT
 * The catalogue is a few dozen kilobytes of pure data that changes when someone deliberately adds
 * footage — roughly never, relative to how often a site is generated. Bundling makes selection a
 * synchronous array filter with no I/O, no cache to warm, and no failure mode on the one code path
 * a customer is watching. A KV read would buy nothing and cost a round trip and an error branch.
 *
 * The BINARIES do not come with it. They live in R2 under exactly the keys the manifest names, and
 * the renderer builds URLs from those keys. Only the index travels in the bundle.
 *
 *   node scripts/media-library/emit-catalogue.mjs
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const MANIFEST = path.join(ROOT, '.media-library', 'media-library.json');
const TARGET = path.join(ROOT, 'packages/core/src/media-library/catalogue.generated.ts');

if (!existsSync(MANIFEST)) {
  console.error(`no manifest at ${path.relative(ROOT, MANIFEST)} — run ingest.mjs first`);
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));

const header = `/**
 * GENERATED by scripts/media-library/emit-catalogue.mjs — do not edit by hand.
 *
 * The pre-optimised media library's index. Every clip and still named here has already been
 * transcoded to every rendition it will be served in, and measured for luminance and hue. The
 * builder reads this as data: no stock API on the critical path, no per-signup quota, no transcode.
 *
 * The binaries live in R2 under exactly these keys. Re-run the ingest to change them; this file is
 * a projection and a hand edit will be overwritten.
 */

import type { MediaLibrary } from './types';

export const MEDIA_LIBRARY: MediaLibrary = `;

// `builtAt` is deliberately dropped from the bundled copy: it changes on every ingest and would
// make the generated file — and therefore the Worker bundle hash — churn for no behavioural reason.
const bundled = {
  version: manifest.version,
  builtAt: '',
  videos: manifest.videos,
  images: manifest.images,
};

writeFileSync(TARGET, `${header}${JSON.stringify(bundled, null, 2)} as const;\n`);
format(TARGET);

const bytes = readFileSync(TARGET).byteLength;
console.log(
  `${manifest.videos.length} clips + ${manifest.images.length} grounds -> ` +
    `${path.relative(ROOT, TARGET)} (${Math.round(bytes / 1024)} kB)`,
);

/**
 * Formats a generated file with the repository's own prettier.
 *
 * Without this the file lands in git as raw `JSON.stringify` output — double-quoted keys, no
 * trailing commas — and `pnpm format:check` fails on a file nobody wrote by hand. It only ever
 * passed before because a human ran `pnpm format` afterwards; a workflow does not, and commits the
 * unformatted version. Missing prettier is not fatal: the file is still correct, just ugly.
 */
function format(file) {
  const prettier = path.join(ROOT, 'node_modules/.bin/prettier');
  if (!existsSync(prettier)) {
    return;
  }
  try {
    execFileSync(prettier, ['--write', file], { stdio: 'ignore' });
  } catch {
    // A formatting failure must not lose the generated file that is already written.
  }
}
